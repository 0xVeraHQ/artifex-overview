#!/usr/bin/env python3
"""Generate the public Artifex tables.

Run by hand, or from a release workflow in artifex-orch. This script lives
in the public presentation repo (0xVeraHQ/artifex-overview). It does not copy
private files into this repo: it reads them, checks them, and writes only
the markdown tables.

  python scripts/generate_tables.py \
    --versions /path/to/artifex-orch/versions.env \
    --registry /path/to/artifex-api/src/contracts/registry.json \
    --digests /path/to/harbor-digests.json

Reads (public, in this repo):
  qa/results.json    case id, description, status, optional Testnet tx hash
  roadmap.yaml       phases and allowed statuses
  wallets.yaml       public project accounts by network
  pieces.yaml        15 demo artworks and on-chain evidence

Reads (private checkouts or a release job; never committed here):
  versions.env       ARTIFEX_API_TAG, ARTIFEX_WEB_UI_TAG
  registry.json      contract ids, version, active flag, platform, validator
  harbor digests     image tag, digest, publish time, cosign identity

Writes (this repo only):
  QA.md, RELEASES.md, CONTRACTS.md, WALLETS.md, ROADMAP.md, PIECES.md
  the status table in README.md between the GENERATED:status markers

Public statuses are PASS, PENDING (reason required), and PLANNED.
FAIL is rejected and nothing is published. An image row is published only
when cosign verification succeeded. Platform and validator addresses in
wallets.yaml must match the active registry.

Intended artifex-orch workflow (add it there when a release should refresh
this repo; do not point it at any other repository):

  on: workflow_dispatch, and after an api or web-ui release
  token: contents:write on 0xVeraHQ/artifex-overview only
  steps:
    1. Check out artifex-orch, artifex-api, and this repo into separate dirs.
    2. The release job writes a digests manifest (tag, digest, cosign).
       The manifest contains no secrets and is not copied here.
    3. Run this script with --versions, --registry, and --digests.
    4. Commit the markdown changes and push with that token.
"""

