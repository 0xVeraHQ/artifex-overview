def replace_status(readme: str, block: str) -> str:
    start = "<!-- GENERATED:status -->"
    end = "<!-- /GENERATED:status -->"
    if start not in readme or end not in readme:
        raise Reject("README.md is missing GENERATED:status markers")
    before, rest = readme.split(start, 1)
    _, after = rest.split(end, 1)
    return f"{before}{start}\n{block}\n{end}{after}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--qa", type=Path, default=None)
    parser.add_argument("--roadmap", type=Path, default=None)
    parser.add_argument("--wallets", type=Path, default=None)
    parser.add_argument("--pieces", type=Path, default=None)
    parser.add_argument("--versions", type=Path, required=True)
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--digests", type=Path, required=True)
    parser.add_argument("--mainnet-deploy", type=Path, default=None)
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        versions = parse_versions(args.versions)
        registry = load_json(args.registry)
        digests = load_json(args.digests)
        mainnet_path = args.mainnet_deploy or root / "sources" / "mainnet.deploy.json"
        mainnet_deploy = None
        if mainnet_path.is_file():
            mainnet_deploy = load_json(mainnet_path)
        qa = load_json(args.qa or root / "qa" / "results.json")
        roadmap = yaml.safe_load((args.roadmap or root / "roadmap.yaml").read_text(encoding="utf-8"))
        wallets = yaml.safe_load((args.wallets or root / "wallets.yaml").read_text(encoding="utf-8"))
        pieces = yaml.safe_load((args.pieces or root / "pieces.yaml").read_text(encoding="utf-8"))
        cases = qa_rows(qa)
        contracts_md, active, mainnet_meta = render_contracts(registry, mainnet_deploy)
        roadmap_md, headline = render_roadmap(roadmap)
        status = render_status(
            qa,
            cases,
            versions,
            str(registry["activeVersion"]),
            str(active["contractsRepoTag"]),
            headline,
            mainnet_meta,
        )
        files = {
            "QA.md": render_qa(qa, cases),
            "RELEASES.md": render_releases(digests, versions),
            "CONTRACTS.md": contracts_md,
            "WALLETS.md": render_wallets(wallets, active),
            "ROADMAP.md": roadmap_md,
            "PIECES.md": render_pieces(pieces),
        }
        for name, text in files.items():
            path = root / name
            if not path.resolve().is_relative_to(root):
                raise Reject(f"refusing to write outside {root}")
            path.write_text(text, encoding="utf-8", newline="\n")
        readme_path = root / "README.md"
        readme = readme_path.read_text(encoding="utf-8")
        readme_path.write_text(replace_status(readme, status), encoding="utf-8", newline="\n")
    except Reject as exc:
        print(f"generate_tables: {exc}", file=sys.stderr)
        return 1
    print(
        "wrote QA.md RELEASES.md CONTRACTS.md WALLETS.md ROADMAP.md PIECES.md "
        "and the README status table"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
