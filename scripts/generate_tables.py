def render_roadmap(doc: dict) -> tuple[str, str]:
    phases = doc.get("phases")
    if not isinstance(phases, list) or not phases:
        raise Reject("roadmap.yaml has no phases")
    rows = []
    headline = "PLANNED"
    for phase in phases:
        name = str(phase.get("name") or "").strip()
        status = str(phase.get("status") or "").strip()
        summary = " ".join(str(phase.get("summary") or "").split())
        items = phase.get("items") or []
        if status not in ALLOWED_PHASE:
            raise Reject(f"{name} status {status!r} is not publishable")
        if not name or not summary or not items:
            raise Reject(f"phase {name or '?'} needs a summary and items")
        if status == "IN PROGRESS":
            headline = name
        item_text = "; ".join(str(item).strip() for item in items)
        rows.append([name, status, item_text])
    if any(p.get("status") == "IN PROGRESS" for p in phases):
        names = [p["name"] for p in phases if p.get("status") == "IN PROGRESS"]
        headline = names[0]
    lines = [
        GENERATED,
        "# Roadmap",
        "",
        "Phases of Artifex after the current Testnet product.",
        "Statuses are **DONE**, **IN PROGRESS**, or **PLANNED**.",
        "",
        table(["Phase", "Status", "Scope"], rows),
        "",
        "The HackMeridian row is the work of the event.",
        "What already existed before the event, and what lands during it,",
        "is recorded in [HACKMERIDIAN.md](HACKMERIDIAN.md) and in the README.",
        "",
    ]
    return "\n".join(lines), headline


def qa_headline(doc: dict, cases: list[dict]) -> str:
    mainnet = doc.get("mainnet") or {}
    mn_status = str(mainnet.get("status") or "").strip().upper()
    if mn_status == "PASS":
        return "PASS — Mainnet run a–g (26/10/2026)"
    verdict = str(doc.get("verdict") or "").strip().upper()
    note = str(doc.get("verdictNote") or "").strip()
    if verdict == "PASS":
        return f"PASS — {note}" if note else "PASS"
    statuses = {case["status"] for case in cases}
    if statuses == {"PASS"}:
        return "PASS"
    if "PENDING" in statuses:
        reasons = sorted({case["reason"] for case in cases if case["status"] == "PENDING"})
        return "PENDING — " + reasons[0]
    if "PLANNED" in statuses:
        return "PLANNED"
    return "PENDING"


