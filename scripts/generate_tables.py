#!/usr/bin/env python3
"""Generate the public Artifex tables.

Run by hand, or from a release workflow in artifex-orch. This script lives
in the public presentation repo. It does not copy private files into this
repo: it reads them, checks them, and writes only the markdown tables.

  python scripts/generate_tables.py \
    --versions /path/to/artifex-orch/versions.env \
    --registry /path/to/artifex-api/src/contracts/registry.json \
    --digests /path/to/harbor-digests.json

Reads (public, in this repo):
  qa/results.json    case id, description, status, optional Testnet tx hash
  roadmap.yaml       phases and allowed statuses
  wallets.yaml       public project accounts

Reads (private checkouts or a release job; never committed here):
  versions.env       ARTIFEX_API_TAG, ARTIFEX_WEB_UI_TAG
  registry.json      contract ids, version, active flag, platform, validator
  harbor digests     image tag, digest, publish time, cosign identity

Writes (this repo only):
  QA.md, RELEASES.md, CONTRACTS.md, WALLETS.md, ROADMAP.md
  the status table in README.md between the GENERATED:status markers

Public statuses are PASS, PENDING (reason required), and PLANNED.
FAIL is rejected and nothing is published. An image row is published only
when cosign verification succeeded. Platform and validator addresses in
wallets.yaml must match the active registry.

Intended artifex-orch workflow (add it there when a release should refresh
this repo; do not point it at any other repository):

  on: workflow_dispatch, and after an api or web-ui release
  token: contents:write on 0xVeraHQ/artifex only
  steps:
    1. Check out artifex-orch, artifex-api, and this repo into separate dirs.
    2. The release job writes a digests manifest (tag, digest, cosign).
       The manifest contains no secrets and is not copied here.
    3. Run this script with --versions, --registry, and --digests.
    4. Commit the markdown changes and push with that token.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
ALLOWED_QA = {"PASS", "PENDING", "PLANNED"}
ALLOWED_PHASE = {"DONE", "IN PROGRESS", "PLANNED"}
GROUP_ORDER = {"V": 0, "C": 1, "S": 2, "N": 3}
GROUP_TITLE = {
    "V": "Visitor",
    "C": "Certification",
    "S": "Sales",
    "N": "Negative cases",
}
TX_RE = re.compile(r"^[0-9a-fA-F]{64}$")
G_RE = re.compile(r"^G[A-Z2-7]{55}$")
C_RE = re.compile(r"^C[A-Z2-7]{55}$")
DIGEST_RE = re.compile(r"^sha256:[0-9a-f]{64}$")
TAG_RE = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+$")

CONTRACT_LABELS = {
    "roles": "Roles",
    "feeCollector": "Fee collector",
    "connoisseur": "Connoisseur authorization",
    "certRegistry": "Certificate registry",
    "wholeNft": "Whole-work NFT",
    "participation": "Participation",
    "marketplace": "Marketplace",
    "distribution": "Distribution",
    "usdcSac": "USDC asset contract",
    "xlmSac": "XLM asset contract",
}

EXPLORER = "https://stellar.expert/explorer/testnet"
GENERATED = "<!-- Generated by scripts/generate_tables.py. Do not edit the tables by hand. -->\n"


class Reject(Exception):
    pass


def cell(value: str) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def table(headers: list[str], rows: list[list[str]]) -> str:
    head = "| " + " | ".join(headers) + " |"
    rule = "| " + " | ".join("---" for _ in headers) + " |"
    body = ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join([head, rule, *body]) + "\n"


def load_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, dict):
        raise Reject(f"{path} must be a JSON object")
    return data


def parse_versions(path: Path) -> dict[str, str]:
    found: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or "=" not in line:
            continue
        key, value = line.split("=", 1)
        found[key.strip()] = value.strip()
    missing = [k for k in ("ARTIFEX_API_TAG", "ARTIFEX_WEB_UI_TAG") if k not in found]
    if missing:
        raise Reject(f"{path} is missing {', '.join(missing)}")
    for key in ("ARTIFEX_API_TAG", "ARTIFEX_WEB_UI_TAG"):
        if not TAG_RE.fullmatch(found[key]):
            raise Reject(f"{key} is not a SemVer tag: {found[key]}")
    return found


def tx_link(tx_hash: str | None) -> str:
    if not tx_hash:
        return "—"
    if not TX_RE.fullmatch(tx_hash):
        raise Reject(f"transaction hash is not 64 hex characters: {tx_hash}")
    digest = tx_hash.lower()
    return f"[{digest[:10]}…]({EXPLORER}/tx/{digest})"


def qa_rows(doc: dict) -> list[dict]:
    cases = doc.get("cases")
    if not isinstance(cases, list) or not cases:
        raise Reject("qa/results.json has no cases")
    seen: set[str] = set()
    cleaned = []
    for case in cases:
        cid = str(case.get("id", "")).strip()
        group = str(case.get("group", "")).strip()
        status = str(case.get("status", "")).strip()
        if group not in GROUP_ORDER:
            raise Reject(f"{cid or '?'} has unknown group {group}")
        if not cid.startswith(group + "-"):
            raise Reject(f"{cid} does not belong to group {group}")
        if cid in seen:
            raise Reject(f"duplicate case {cid}")
        seen.add(cid)
        if status not in ALLOWED_QA:
            raise Reject(
                f"{cid} status {status!r} is not publishable "
                "(allowed: PASS, PENDING, PLANNED)"
            )
        reason = str(case.get("reason") or "").strip()
        if status in {"PENDING", "PLANNED"} and not reason:
            raise Reject(f"{cid} is {status} and needs a reason")
        if status == "PASS" and reason:
            raise Reject(f"{cid} is PASS and must not carry a reason")
        title = str(case.get("title") or "").strip()
        description = str(case.get("description") or "").strip()
        if not title or not description:
            raise Reject(f"{cid} needs a title and a description")
        tx_hash = case.get("txHash") or case.get("tx_hash") or None
        if tx_hash is not None:
            tx_hash = str(tx_hash).strip() or None
        cleaned.append(
            {
                "id": cid,
                "group": group,
                "title": title,
                "description": description,
                "status": status,
                "reason": reason,
                "tx": tx_link(tx_hash),
            }
        )
    cleaned.sort(key=lambda row: (GROUP_ORDER[row["group"]], row["id"]))
    return cleaned


def render_qa(cases: list[dict]) -> str:
    lines = [
        GENERATED,
        "# QA",
        "",
        "Black-box checks of the public site and Stellar Testnet.",
        "An independent agent runs them with no access to the source code.",
        "",
        "A case is published as **PASS** (with a Testnet transaction link when the check produces one), **PENDING** (with a reason), or **PLANNED**.",
        "A result outside those three states is rejected by the generator and is not written here.",
        "",
        f"Network: [Stellar Testnet]({EXPLORER}).",
        "",
    ]
    current = None
    bucket: list[list[str]] = []

    def flush() -> None:
        if bucket:
            lines.append(
                table(
                    ["Case", "Check", "Status", "Reason", "Testnet transaction"],
                    bucket,
                )
            )
            lines.append("")
            bucket.clear()

    for case in cases:
        if case["group"] != current:
            flush()
            current = case["group"]
            lines.append(f"## {current} — {GROUP_TITLE[current]}")
            lines.append("")
        bucket.append(
            [
                case["id"],
                f"**{case['title']}.** {case['description']}",
                case["status"],
                case["reason"] or "—",
                case["tx"],
            ]
        )
    flush()
    counts: dict[str, int] = {}
    for case in cases:
        counts[case["status"]] = counts.get(case["status"], 0) + 1
    summary = ", ".join(f"{counts[k]} {k}" for k in ("PASS", "PENDING", "PLANNED") if k in counts)
    lines.append(f"{len(cases)} cases: {summary}.")
    lines.append("")
    return "\n".join(lines)


def render_releases(digests: dict, versions: dict[str, str]) -> str:
    registry = str(digests.get("registry") or "").strip()
    project = str(digests.get("project") or "").strip()
    images = digests.get("images")
    if not registry or "/" in registry or " " in registry:
        raise Reject("digests.registry must be a registry hostname")
    if not project or "/" in project:
        raise Reject("digests.project must be a registry project name")
    if not isinstance(images, list) or not images:
        raise Reject("digests.images is empty")
    expected = {
        "artifex-api": versions["ARTIFEX_API_TAG"],
        "artifex-web-ui": versions["ARTIFEX_WEB_UI_TAG"],
    }
    order = {"artifex-api": 0, "artifex-web-ui": 1}
    images.sort(key=lambda item: order.get(str(item.get("name")), 99))
    rows = []
    seen = set()
    for image in images:
        name = str(image.get("name") or "").strip()
        tag = str(image.get("tag") or "").strip()
        digest = str(image.get("digest") or "").strip()
        published = str(image.get("publishedAt") or "").strip()
        cosign = image.get("cosign") or {}
        if name not in expected:
            raise Reject(f"unexpected image {name}")
        if seen & {name}:
            raise Reject(f"duplicate image {name}")
        seen.add(name)
        if tag != expected[name]:
            raise Reject(
                f"{name} digest tag {tag} does not match versions.env {expected[name]}"
            )
        if not DIGEST_RE.fullmatch(digest):
            raise Reject(f"{name} digest is not sha256:<64 hex>")
        if not published:
            raise Reject(f"{name} has no publishedAt")
        if cosign.get("verified") is not True:
            raise Reject(f"{name} is not cosign-verified; refusing to publish it")
        identity = str(cosign.get("identity") or "").strip()
        issuer = str(cosign.get("oidcIssuer") or "").strip()
        if not identity.startswith("https://github.com/0xVeraHQ/") or "docker-release.yml@refs/tags/v" not in identity:
            raise Reject(f"{name} cosign identity is not the Artifex release workflow")
        if issuer != "https://token.actions.githubusercontent.com":
            raise Reject(f"{name} cosign issuer is not GitHub Actions")
        if f"refs/tags/v{tag}" not in identity:
            raise Reject(f"{name} cosign identity does not match tag {tag}")
        ref = f"{registry}/{project}/{name}@{digest}"
        rows.append(
            [
                f"`{registry}/{project}/{name}`",
                tag,
                f"`{digest}`",
                published[:10],
                "Verified, keyless",
            ]
        )
        image["_ref"] = ref
        image["_identity"] = identity
    if seen != set(expected):
        raise Reject(f"digests missing images: {set(expected) - seen}")
    verify = []
    for image in images:
        repo = "artifex-api" if image["name"] == "artifex-api" else "artifex-web-ui"
        verify.append(
            "```bash\n"
            "cosign verify \\\n"
            "  --certificate-identity-regexp \\\n"
            f"    '^https://github.com/0xVeraHQ/{repo}/\\.github/workflows/docker-release\\.yml@refs/tags/v.+$' \\\n"
            "  --certificate-oidc-issuer https://token.actions.githubusercontent.com \\\n"
            f"  {image['_ref']}\n"
            "```"
        )
    lines = [
        GENERATED,
        "# Releases",
        "",
        "Harbor images for the running Testnet deployment.",
        "The tag is the tag the site is running. Digests and the cosign check come from the release job.",
        "Contract Wasm is not an image;",
        "its tag is in [CONTRACTS.md](CONTRACTS.md).",
        "",
        f"Registry: `{registry}` · project: `{project}`.",
        "",
        "Each image is signed keyless with cosign. The signing identity is the GitHub Actions",
        "workflow `docker-release.yml` on the matching `vX.Y.Z` tag, issued by",
        "`https://token.actions.githubusercontent.com`.",
        "",
        table(
            ["Image", "Tag", "Digest", "Published", "Cosign"],
            rows,
        ),
        "",
        "## Check a signature",
        "",
        "Cosign 2.x. The command checks the digest, not the moving tag.",
        "",
        "\n\n".join(verify),
        "",
    ]
    return "\n".join(lines)


def render_contracts(registry: dict) -> tuple[str, dict]:
    active_id = str(registry.get("activeVersion") or "")
    versions = registry.get("versions")
    if not isinstance(versions, dict) or active_id not in versions:
        raise Reject("registry has no active version")
    rows = []
    active = None
    for vid, spec in versions.items():
        if spec.get("network") != "testnet":
            raise Reject(f"{vid} is not testnet")
        tag = str(spec.get("contractsRepoTag") or "")
        if not tag:
            raise Reject(f"{vid} has no contracts repo tag")
        is_active = bool(spec.get("active"))
        if is_active:
            if active is not None:
                raise Reject("more than one registry version is active")
            if vid != active_id:
                raise Reject("active flag does not match activeVersion")
            active = spec
        contracts = spec.get("contracts") or {}
        for key, label in CONTRACT_LABELS.items():
            cid = str(contracts.get(key) or "")
            if not C_RE.fullmatch(cid):
                raise Reject(f"{vid} {key} is not a contract id")
            rows.append(
                [
                    label,
                    vid,
                    tag,
                    f"`{cid}`",
                    "Yes" if is_active else "No",
                    f"[Explorer]({EXPLORER}/contract/{cid})",
                ]
            )
    if active is None:
        raise Reject("no active contract version")
    for field in ("platform", "validator"):
        addr = str(active.get(field) or "")
        if not G_RE.fullmatch(addr):
            raise Reject(f"active {field} is not a public account")
    lines = [
        GENERATED,
        "# Contracts",
        "",
        "Soroban contracts on Stellar Testnet. The active set is the one the public API serves:",
        "",
        "https://artifex.0xvera.com/api/contracts/registry",
        "",
        f"Active registry version: **{active_id}**. Contracts repository tag: **{active['contractsRepoTag']}**.",
        "USDC and XLM rows are Stellar asset contracts used for payment, not Artifex business contracts.",
        "Inactive versions stay listed so a judge can see what they replaced.",
        "",
        table(
            ["Contract", "Registry version", "Contracts tag", "ID", "Active", "Explorer"],
            rows,
        ),
        "",
    ]
    return "\n".join(lines), active


def render_wallets(doc: dict, active: dict) -> str:
    if doc.get("network") != "testnet":
        raise Reject("wallets.yaml network must be testnet")
    accounts = doc.get("accounts")
    if not isinstance(accounts, list) or not accounts:
        raise Reject("wallets.yaml has no accounts")
    rows = []
    seen = set()
    for account in accounts:
        role = str(account.get("role") or "").strip()
        address = str(account.get("address") or "").strip()
        purpose = " ".join(str(account.get("purpose") or "").split())
        field = account.get("registryField")
        if not role or not purpose:
            raise Reject("each wallet needs a role and a purpose")
        if not G_RE.fullmatch(address):
            raise Reject(f"{role} address is not a public account")
        if address in seen and field not in {"platform", "validator"}:
            raise Reject(f"duplicate account {address}")
        seen.add(address)
        if field:
            expected = str(active.get(field) or "")
            if address != expected:
                raise Reject(
                    f"wallets.yaml {field} {address} does not match the active registry {expected}"
                )
        rows.append(
            [
                role,
                f"`{address}`",
                purpose,
                f"[Explorer]({EXPLORER}/account/{address})",
            ]
        )
    lines = [
        GENERATED,
        "# Wallets",
        "",
        "Public accounts for the Testnet deployment.",
        "",
        table(["Role", "Address", "Purpose", "Explorer"], rows),
        "",
        "The Circle Testnet USDC issuer used for payments is",
        "`GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5`.",
        "That account is Circle's, not an Artifex account. See [TRY-IT.md](TRY-IT.md).",
        "",
    ]
    return "\n".join(lines)


def render_roadmap(doc: dict) -> tuple[str, str]:
    phases = doc.get("phases")
    if not isinstance(phases, list) or not phases:
        raise Reject("roadmap.yaml has no phases")
    rows = []
    headline = "PLANNED"
    for phase in phases:
        name = str(phase.get("name") or "").strip()
        status = str(phase.get("status") or "").strip()
        summary = " ".join(str(phase.get("summary") or "").split())
        items = phase.get("items") or []
        if status not in ALLOWED_PHASE:
            raise Reject(f"{name} status {status!r} is not publishable")
        if not name or not summary or not items:
            raise Reject(f"phase {name or '?'} needs a summary and items")
        if status == "IN PROGRESS":
            headline = name
        item_text = "; ".join(str(item).strip() for item in items)
        rows.append([name, status, item_text])
    if any(p.get("status") == "IN PROGRESS" for p in phases):
        names = [p["name"] for p in phases if p.get("status") == "IN PROGRESS"]
        headline = names[0]
    lines = [
        GENERATED,
        "# Roadmap",
        "",
        "Phases of Artifex after the current Testnet product.",
        "Statuses are **DONE**, **IN PROGRESS**, or **PLANNED**.",
        "",
        table(["Phase", "Status", "Scope"], rows),
        "",
        "The HackMeridian row is the work of the event.",
        "What already existed before the event, and what lands during it,",
        "is recorded in the README on Sunday 25 October 2026.",
        "",
    ]
    return "\n".join(lines), headline


def qa_headline(cases: list[dict]) -> str:
    statuses = {case["status"] for case in cases}
    if statuses == {"PASS"}:
        return "PASS"
    if "PENDING" in statuses:
        reasons = sorted({case["reason"] for case in cases if case["status"] == "PENDING"})
        return "PENDING — " + reasons[0]
    if "PLANNED" in statuses:
        return "PLANNED"
    return "PENDING"


def render_status(cases, versions, active_version: str, contracts_tag: str, roadmap_headline: str) -> str:
    rows = [
        [
            "QA",
            qa_headline(cases),
            "[QA.md](QA.md)",
        ],
        [
            "Latest release",
            f"api {versions['ARTIFEX_API_TAG']}, web {versions['ARTIFEX_WEB_UI_TAG']}, cosign verified",
            "[RELEASES.md](RELEASES.md)",
        ],
        [
            "Active contracts",
            f"Registry {active_version} on Testnet, contracts tag {contracts_tag}",
            "[CONTRACTS.md](CONTRACTS.md)",
        ],
        [
            "Roadmap",
            f"{roadmap_headline} in progress"
            if roadmap_headline not in {"PLANNED", "DONE"}
            else roadmap_headline,
            "[ROADMAP.md](ROADMAP.md)",
        ],
    ]
    return table(["Area", "State", "Document"], rows)


def replace_status(readme: str, block: str) -> str:
    start = "<!-- GENERATED:status -->"
    end = "<!-- /GENERATED:status -->"
    if start not in readme or end not in readme:
        raise Reject("README.md is missing GENERATED:status markers")
    before, rest = readme.split(start, 1)
    _, after = rest.split(end, 1)
    return f"{before}{start}\n{block}\n{end}{after}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--qa", type=Path, default=None)
    parser.add_argument("--roadmap", type=Path, default=None)
    parser.add_argument("--wallets", type=Path, default=None)
    parser.add_argument("--versions", type=Path, required=True)
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--digests", type=Path, required=True)
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        versions = parse_versions(args.versions)
        registry = load_json(args.registry)
        digests = load_json(args.digests)
        qa = load_json(args.qa or root / "qa" / "results.json")
        roadmap = yaml.safe_load((args.roadmap or root / "roadmap.yaml").read_text(encoding="utf-8"))
        wallets = yaml.safe_load((args.wallets or root / "wallets.yaml").read_text(encoding="utf-8"))
        cases = qa_rows(qa)
        contracts_md, active = render_contracts(registry)
        roadmap_md, headline = render_roadmap(roadmap)
        status = render_status(
            cases,
            versions,
            str(registry["activeVersion"]),
            str(active["contractsRepoTag"]),
            headline,
        )
        files = {
            "QA.md": render_qa(cases),
            "RELEASES.md": render_releases(digests, versions),
            "CONTRACTS.md": contracts_md,
            "WALLETS.md": render_wallets(wallets, active),
            "ROADMAP.md": roadmap_md,
        }
        for name, text in files.items():
            path = root / name
            if not path.resolve().is_relative_to(root):
                raise Reject(f"refusing to write outside {root}")
            path.write_text(text, encoding="utf-8", newline="\n")
        readme_path = root / "README.md"
        readme = readme_path.read_text(encoding="utf-8")
        readme_path.write_text(replace_status(readme, status), encoding="utf-8", newline="\n")
    except Reject as exc:
        print(f"generate_tables: {exc}", file=sys.stderr)
        return 1
    print("wrote QA.md RELEASES.md CONTRACTS.md WALLETS.md ROADMAP.md and the README status table")
    return 0


if __name__ == "__main__":
    sys.exit(main())
