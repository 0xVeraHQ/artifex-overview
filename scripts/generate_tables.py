EXPLORERS = {
    "testnet": "https://stellar.expert/explorer/testnet",
    "mainnet": "https://stellar.expert/explorer/public",
    "public": "https://stellar.expert/explorer/public",
}
GENERATED = "<!-- Generated by scripts/generate_tables.py. Do not edit the tables by hand. -->\n"


class Reject(Exception):
    pass


def cell(value: str) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def table(headers: list[str], rows: list[list[str]]) -> str:
    head = "| " + " | ".join(headers) + " |"
    rule = "| " + " | ".join("---" for _ in headers) + " |"
    body = ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join([head, rule, *body]) + "\n"


def load_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, dict):
        raise Reject(f"{path} must be a JSON object")
    return data


def parse_versions(path: Path) -> dict[str, str]:
    found: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or "=" not in line:
            continue
        key, value = line.split("=", 1)
        found[key.strip()] = value.strip()
    missing = [k for k in ("ARTIFEX_API_TAG", "ARTIFEX_WEB_UI_TAG") if k not in found]
    if missing:
        raise Reject(f"{path} is missing {', '.join(missing)}")
    for key in ("ARTIFEX_API_TAG", "ARTIFEX_WEB_UI_TAG"):
        if not TAG_RE.fullmatch(found[key]):
            raise Reject(f"{key} is not a SemVer tag: {found[key]}")
    return found


def explorer_for(network: str) -> str:
    key = network.strip().lower()
    if key not in EXPLORERS:
        raise Reject(f"unknown network {network}")
    return EXPLORERS[key]


def tx_link(tx_hash: str | None, network: str = "testnet") -> str:
    if not tx_hash:
        return "—"
    if not TX_RE.fullmatch(tx_hash):
        raise Reject(f"transaction hash is not 64 hex characters: {tx_hash}")
    digest = tx_hash.lower()
    return f"[{digest[:10]}…]({explorer_for(network)}/tx/{digest})"


def qa_rows(doc: dict) -> list[dict]:
    cases = doc.get("cases")
    if not isinstance(cases, list) or not cases:
        raise Reject("qa/results.json has no cases")
    seen: set[str] = set()
    cleaned = []
    for case in cases:
        cid = str(case.get("id", "")).strip()
        group = str(case.get("group", "")).strip()
        status = str(case.get("status", "")).strip()
        if group not in GROUP_ORDER:
            raise Reject(f"{cid or '?'} has unknown group {group}")
        if not cid.startswith(group + "-"):
            raise Reject(f"{cid} does not belong to group {group}")
        if cid in seen:
            raise Reject(f"duplicate case {cid}")
        seen.add(cid)
        if status not in ALLOWED_QA:
            raise Reject(
                f"{cid} status {status!r} is not publishable "
                "(allowed: PASS, PENDING, PLANNED)"
            )
        reason = str(case.get("reason") or "").strip()
        if status in {"PENDING", "PLANNED"} and not reason:
            raise Reject(f"{cid} is {status} and needs a reason")
        if status == "PASS" and reason:
            raise Reject(f"{cid} is PASS and must not carry a reason")
        title = str(case.get("title") or "").strip()
        description = str(case.get("description") or "").strip()
        if not title or not description:
            raise Reject(f"{cid} needs a title and a description")
        tx_hash = case.get("txHash") or case.get("tx_hash") or None
        if tx_hash is not None:
            tx_hash = str(tx_hash).strip() or None
        cleaned.append(
            {
                "id": cid,
                "group": group,
                "title": title,
                "description": description,
                "status": status,
                "reason": reason,
                "tx": tx_link(tx_hash),
            }
        )
    cleaned.sort(key=lambda row: (GROUP_ORDER[row["group"]], row["id"]))
    return cleaned


def render_qa(doc: dict, cases: list[dict]) -> str:
    history = doc.get("history") or []
    verdict = str(doc.get("verdict") or "").strip().upper()
    verdict_note = str(doc.get("verdictNote") or "").strip()
    lines = [
        GENERATED,
        "# QA",
        "",
        "## Methodology",
        "",
        "Black-box checks of the public site on **Stellar mainnet** (primary for judges)",
        "and earlier Testnet passes used as development history.",
        "An independent agent runs them with no access to the source code,",
        "the private repositories, or the server.",
        "",
        "A case is published as **PASS** (with an explorer transaction link when the check produces one), **PENDING** (with a reason), or **PLANNED**.",
        "A result outside those three states is rejected by the generator and is not written here.",
        "",
        f"Mainnet explorer: [stellar.expert/public]({explorer_for('mainnet')}).",
        f"Testnet history: [stellar.expert/testnet]({explorer_for('testnet')}).",
        "",
    ]
    if verdict == "PASS":
        lines.extend(
            [
                f"**Verdict: PASS** — {verdict_note}." if verdict_note else "**Verdict: PASS**.",
                "",
            ]
        )

    mainnet = doc.get("mainnet") or {}
    run = mainnet.get("run") if isinstance(mainnet, dict) else None
    if isinstance(run, dict) and run.get("steps"):
        title = str(run.get("title") or "Mainnet run").strip()
        lines.extend(
            [
                f"## {title}",
                "",
                str(run.get("summary") or "").strip(),
                "",
                f"**Verdict: {run.get('verdict', mainnet.get('status', 'PASS'))}**"
                + (
                    f" — {run.get('txCount')} Horizon-successful transactions;"
                    f" {run.get('feesXlm')} XLM total fees."
                    if run.get("txCount") or run.get("feesXlm")
                    else "."
                ),
                "",
            ]
        )
        run_rows = []
        for row in run["steps"]:
            step = str(row.get("step") or "—")
            action = str(row.get("action") or "—")
            wallet = str(row.get("wallet") or "—")
            movement = str(row.get("movement") or "—")
            txh = row.get("txHash") or row.get("tx_hash")
            if txh:
                cell = tx_link(txh, "mainnet")
            elif row.get("verifyUrl"):
                cell = f"[Verify]({row['verifyUrl']})"
            else:
                cell = "—"
            run_rows.append([step, action, wallet, cell, movement])
        lines.append(
            table(
                ["Paso", "Acción", "Wallet", "Tx", "Movimiento"],
                run_rows,
            )
        )
        lines.append("")
        issues = run.get("knownIssues") or []
        if issues:
            lines.extend(
                [
                    "### Known issues (non-blocking UI)",
                    "",
                    "Seven interface findings that did not block the Mainnet run verdict.",
                    "Tracked on the [roadmap](ROADMAP.md).",
                    "",
                ]
            )
            issue_rows = []
            for issue in issues:
                rid = str(issue.get("id") or "—")
                ititle = str(issue.get("title") or "—")
                detail = str(issue.get("detail") or "—")
                road = str(issue.get("roadmap") or "ROADMAP.md")
                issue_rows.append([rid, ititle, detail, f"[Roadmap]({road})"])
            lines.append(
                table(["Id", "Issue", "Detail", "Roadmap"], issue_rows)
            )
            lines.append("")
    elif mainnet:
        lines.extend(
            [
                "## Mainnet",
                "",
                f"**{mainnet.get('status', 'PENDING')}** — {mainnet.get('reason', 'mainnet launch at HackMeridian')}.",
                "",
            ]
        )

    smoke = (mainnet.get("smoke") or []) if isinstance(mainnet, dict) else []
    if isinstance(smoke, list) and smoke:
        lines.extend(
            [
                "### Mainnet smoke checklist",
                "",
            ]
        )
        smoke_rows = []
        for row in smoke:
            rid = str(row.get("id") or "").strip() or "—"
            title = str(row.get("title") or "").strip() or "—"
            status = str(row.get("status") or "PENDING").strip()
            reason = str(row.get("reason") or "").strip() or "—"
            tx = tx_link(row.get("txHash") or row.get("tx_hash"), "mainnet")
            if status not in ALLOWED_QA:
                raise Reject(f"mainnet smoke {rid} status {status!r} is not publishable")
            if status in {"PENDING", "PLANNED"} and reason == "—":
                raise Reject(f"mainnet smoke {rid} needs a reason")
            smoke_rows.append([rid, title, status, reason, tx])
        lines.append(
            table(
                ["Check", "What", "Status", "Reason", "Mainnet transaction"],
                smoke_rows,
            )
        )
        lines.append("")

    lines.extend(
        [
            "## Pass history (Testnet)",
            "",
        ]
    )
    if history:
        hist_rows = []
        for row in history:
            hist_rows.append(
                [
                    str(row.get("date") or ""),
                    str(row.get("pass") or ""),
                    "" if row.get("validated") is None else str(row.get("validated")),
                    "" if row.get("blockers") is None else str(row.get("blockers")),
                    str(row.get("note") or "—"),
                ]
            )
        lines.append(
            table(
                ["Date", "Pass", "Validated", "Blockers", "Note"],
                hist_rows,
            )
        )
        lines.append("")
    else:
        lines.append("No pass history recorded yet.")
        lines.append("")

    lines.append("## Cases (Testnet history)")
    lines.append("")
    current = None
    bucket: list[list[str]] = []

    def flush() -> None:
        if bucket:
            lines.append(
                table(
                    ["Case", "Check", "Status", "Reason", "Testnet transaction"],
                    bucket,
                )
            )
            lines.append("")
            bucket.clear()

    for case in cases:
        if case["group"] != current:
            flush()
            current = case["group"]
            lines.append(f"### {current} — {GROUP_TITLE[current]}")
            lines.append("")
        bucket.append(
            [
                case["id"],
                f"**{case['title']}.** {case['description']}",
                case["status"],
                case["reason"] or "—",
                case["tx"],
            ]
        )
    flush()
    counts: dict[str, int] = {}
    for case in cases:
        counts[case["status"]] = counts.get(case["status"], 0) + 1
    summary = ", ".join(
        f"{counts[k]} {k}" for k in ("PASS", "PENDING", "PLANNED") if k in counts
    )
    lines.append(f"{len(cases)} cases: {summary}.")
    lines.append("")
    return "\n".join(lines)


def _validate_digest_image(image: dict, registry: str, project: str) -> dict:
    name = str(image.get("name") or "").strip()
    tag = str(image.get("tag") or "").strip()
    digest = str(image.get("digest") or "").strip()
    published = str(image.get("publishedAt") or "").strip()
    cosign = image.get("cosign") or {}
    if name not in {"artifex-api", "artifex-web-ui"}:
        raise Reject(f"unexpected image {name}")
    if not TAG_RE.fullmatch(tag):
        raise Reject(f"{name} tag {tag!r} is not SemVer")
    if not DIGEST_RE.fullmatch(digest):
        raise Reject(f"{name} digest is not sha256:<64 hex>")
    if not published:
        raise Reject(f"{name}:{tag} has no publishedAt")
    if cosign.get("verified") is not True:
        raise Reject(f"{name}:{tag} is not cosign-verified; refusing to publish it")
    identity = str(cosign.get("identity") or "").strip()
    issuer = str(cosign.get("oidcIssuer") or "").strip()
    if not identity.startswith("https://github.com/0xVeraHQ/") or "docker-release.yml@refs/tags/v" not in identity:
        raise Reject(f"{name}:{tag} cosign identity is not the Artifex release workflow")
    if issuer != "https://token.actions.githubusercontent.com":
        raise Reject(f"{name}:{tag} cosign issuer is not GitHub Actions")
    if f"refs/tags/v{tag}" not in identity:
        raise Reject(f"{name}:{tag} cosign identity does not match tag {tag}")
    return {
        "name": name,
        "tag": tag,
        "digest": digest,
        "published": published,
        "note": " ".join(str(image.get("note") or "").split()),
        "ref": f"{registry}/{project}/{name}@{digest}",
    }


def render_releases(digests: dict, versions: dict[str, str]) -> str:
    registry = str(digests.get("registry") or "").strip()
    project = str(digests.get("project") or "").strip()
    images = digests.get("images")
    history = digests.get("history") or []
    if not registry or "/" in registry or " " in registry:
        raise Reject("digests.registry must be a registry hostname")
    if not project or "/" in project:
        raise Reject("digests.project must be a registry project name")
    if not isinstance(images, list) or not images:
        raise Reject("digests.images is empty")
    if not isinstance(history, list):
        raise Reject("digests.history must be a list when present")
    expected = {
        "artifex-api": versions["ARTIFEX_API_TAG"],
        "artifex-web-ui": versions["ARTIFEX_WEB_UI_TAG"],
    }
    current: list[dict] = []
    seen_current: set[str] = set()
    for image in images:
        row = _validate_digest_image(image, registry, project)
        if row["name"] in seen_current:
            raise Reject(f"duplicate current image {row['name']}")
        if row["tag"] != expected[row["name"]]:
            raise Reject(
                f"{row['name']} digest tag {row['tag']} does not match versions.env {expected[row['name']]}"
            )
        seen_current.add(row["name"])
        current.append(row)
    if seen_current != set(expected):
        raise Reject(f"digests missing images: {set(expected) - seen_current}")
    historical: list[dict] = []
    for image in history:
        historical.append(_validate_digest_image(image, registry, project))
    display = current + historical
    display.sort(
        key=lambda item: (
            0 if item["name"] == "artifex-api" else 1,
            tuple(-int(p) for p in item["tag"].split(".")),
        )
    )
    rows = []
    for image in display:
        note = image["note"] or ("Current orch tag" if image["tag"] == expected[image["name"]] else "—")
        rows.append(
            [
                f"`{registry}/{project}/{image['name']}`",
                image["tag"],
                f"`{image['digest']}`",
                image["published"][:10],
                "Verified, keyless",
                note,
            ]
        )
    verify = []
    for image in current:
        repo = "artifex-api" if image["name"] == "artifex-api" else "artifex-web-ui"
        verify.append(
            "```bash\n"
            "cosign verify \\\n"
            "  --certificate-identity-regexp \\\n"
            f"    '^https://github.com/0xVeraHQ/{repo}/\\.github/workflows/docker-release\\.yml@refs/tags/v.+$' \\\n"
            "  --certificate-oidc-issuer https://token.actions.githubusercontent.com \\\n"
            f"  {image['ref']}\n"
            "```"
        )
    lines = [
        GENERATED,
        "# Releases",
        "",
        "Harbor images for Artifex. Current rows match `versions.env` in artifex-orch.",
        "History rows keep cosign-verified digests used during HackMeridian (Testnet QA gate).",
        "Contract Wasm is not an image; its tag is in [CONTRACTS.md](CONTRACTS.md).",
        "",
        f"Registry: `{registry}` · project: `{project}`.",
        "",
        "Each image is signed keyless with cosign. The signing identity is the GitHub Actions",
        "workflow `docker-release.yml` on the matching `vX.Y.Z` tag, issued by",
        "`https://token.actions.githubusercontent.com`.",
        "",
        table(
            ["Image", "Tag", "Digest", "Published", "Cosign", "Note"],
            rows,
        ),
        "",
        "## Check a signature",
        "",
        "Cosign 2.x. The command checks the digest, not the moving tag.",
        "",
        "\n\n".join(verify),
        "",
    ]
    return "\n".join(lines)


